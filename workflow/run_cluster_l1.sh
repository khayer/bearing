#!/usr/bin/env bash
# ----------------------------------------------------------------------
# File     : workflow/run_cluster_l1.sh
# Version  : 1.0.1
# Date     : 2026-10-12 (1.0.1: clears an inherited PYTHONPATH)
# Authors  : Katharina E. Hayer (katharinaehayer@gmail.com) and Claude
#            (Anthropic), co-created
# ----------------------------------------------------------------------
#
# run_cluster_l1.sh -- rebuild every result with the non-cancelling
# differential statistic (config diff_stat: l1, bearing_pvalue.py --diff-stat
# l1) in a NEW results folder, reusing the expensive statistic-independent
# upstream of an existing run (per-sample scores, the 100 permutation rounds,
# the compare/ diff qcats) instead of recomputing them.
#
# WHY: the original per-bin differential tests |sum_i d_i|, which cancels when
# one track's gain is another's loss (benchmark/complementarity_benchmark.py:
# a switch between two equally divergent compositions scores ~0). l1 tests
# sum_i |d_i|. Scores, permutations and the diff qcats do not depend on the
# statistic, so they are linked, not recomputed.
#
# WHAT IT DOES
#   1. Writes workflow/config/config_<dest>.generated.yaml: the source run's
#      config with outdir = DEST and diff_stat = l1 (nothing else changes).
#   2. Creates DEST and SYMLINKS into it, read-only by intent, only:
#        perm/  compare/  consensusQ/compare/  <sample>.qcat.bgz(.tbi)
#        <sample>_cats.json  blacklist/  and the sentinels score.done,
#        perm.done, perm_diff.done, compare.done, consensusQ/compare.done,
#        score_provenance.done
#      Each link gets its target's mtime (touch -h -r), so Snakemake sees the
#      original ordering. Sample sheets are COPIED (cp -p), not linked.
#      Everything else (p-values, calibration, regional, Hi-C overlays,
#      figures, tables) is rebuilt in DEST.
#   3. Dry run. ABORTS if any job would rebuild a linked upstream product
#      (score, perm, compare): those jobs would write through the links into
#      the source run.
#   4. Submits `all` to SLURM (skip with --dry).
#
# USAGE (from the repository root)
#   bash workflow/run_cluster_l1.sh --source results_prior1_n100 \
#        --source-config workflow/config/config_prior1.generated.yaml [--dry]
#   DEST defaults to <source>_l1. The source config must be the one the
#   source run was built with (prior_strength 1, n_perms 100); it is checked.
#
# ASCII-only.

set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WF="$REPO/workflow"
PROFILE="$WF/profiles/slurm"
SRC=""; SRC_CONFIG=""; DEST=""; DRY=0; SMK=${SNAKEMAKE:-snakemake}
# A loaded environment module (e.g. R/4.4.0 pulls in an EasyBuild SciPy-bundle)
# can put another Python's site-packages on PYTHONPATH; snakemake and the
# pipeline scripts then import an incompatible pandas/numpy. The pipeline does
# not use PYTHONPATH, so clear it.
if [ -n "${PYTHONPATH:-}" ]; then
  echo "NOTE: clearing PYTHONPATH (was: $PYTHONPATH)"
  unset PYTHONPATH
fi

while [ $# -gt 0 ]; do
  case "$1" in
    --source) SRC="$2"; shift 2 ;;
    --source-config) SRC_CONFIG="$2"; shift 2 ;;
    --dest) DEST="$2"; shift 2 ;;
    --dry) DRY=1; shift ;;
    -h|--help) sed -n 2,45p "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done
[ -n "$SRC" ] || { echo "ERROR: --source <results dir under workflow/> is required" >&2; exit 2; }
[ -n "$SRC_CONFIG" ] || { echo "ERROR: --source-config <yaml the source run used> is required" >&2; exit 2; }
SRC="${SRC%/}"; [ -n "$DEST" ] || DEST="${SRC}_l1"
SRC_ABS="$WF/$SRC"; DEST_ABS="$WF/$DEST"
[ -d "$SRC_ABS" ] || { echo "ERROR: source run not found: $SRC_ABS" >&2; exit 1; }
[ -f "$SRC_CONFIG" ] || { echo "ERROR: source config not found: $SRC_CONFIG" >&2; exit 1; }
for f in score.done perm.done perm_diff.done compare.done; do
  [ -e "$SRC_ABS/$f" ] || { echo "ERROR: $SRC_ABS/$f missing: the source run is not complete" >&2; exit 1; }
done
if [ -e "$DEST_ABS" ] && [ "$(ls -A "$DEST_ABS" 2>/dev/null)" ]; then
  echo "NOTE: $DEST_ABS exists and is not empty; linking only what is missing."
fi

NEW_CONFIG="$WF/config/config_${DEST}.generated.yaml"
python3 - "$SRC_CONFIG" "$NEW_CONFIG" "$SRC" "$DEST" << 'PY'
import sys, yaml
src_cfg, new_cfg, src, dest = sys.argv[1:5]
cfg = yaml.safe_load(open(src_cfg))
if str(cfg.get("outdir", "")).rstrip("/") != src:
    sys.exit("ERROR: %s has outdir %r, not %r: pass the config the source run "
             "was built with" % (src_cfg, cfg.get("outdir"), src))
print("  source  : outdir %s  prior_strength %s  n_perms %s  min_signal %s  "
      "pvalue_min_signal %s  diff_stat %s"
      % (cfg.get("outdir"), cfg.get("prior_strength"), cfg.get("n_perms"),
         cfg.get("min_signal"), cfg.get("pvalue_min_signal"),
         cfg.get("diff_stat", "sum")))
cfg["outdir"] = dest
cfg["diff_stat"] = "l1"
with open(new_cfg, "w") as fh:
    fh.write("# AUTO-GENERATED by run_cluster_l1.sh from %s.\n"
             "# Differs from it ONLY in: outdir (%s -> %s), diff_stat (l1).\n"
             % (src_cfg, src, dest))
    yaml.safe_dump(cfg, fh, default_flow_style=False, sort_keys=False)
print("  new     : %s (outdir %s, diff_stat l1)" % (new_cfg, dest))
PY

echo "== linking statistic-independent upstream: $SRC -> $DEST"
mkdir -p "$DEST_ABS/consensusQ"
link() {  # relative path inside the run
  local rel="$1"
  [ -e "$SRC_ABS/$rel" ] || return 0
  [ -e "$DEST_ABS/$rel" ] || [ -L "$DEST_ABS/$rel" ] && return 0
  mkdir -p "$(dirname "$DEST_ABS/$rel")"
  ln -s "$SRC_ABS/$rel" "$DEST_ABS/$rel"
  touch -h -r "$SRC_ABS/$rel" "$DEST_ABS/$rel"
  echo "   link $rel"
}
link blacklist
for f in "$SRC_ABS"/*.qcat.bgz "$SRC_ABS"/*.qcat.bgz.tbi "$SRC_ABS"/*_cats.json; do
  [ -e "$f" ] && link "$(basename "$f")"
done
link perm
link compare
link consensusQ/compare
for s in score.done score_provenance.done perm.done perm_diff.done compare.done \
         consensusQ/compare.done; do
  link "$s"
done
for s in samples.bearing.tsv samples.qcat.tsv; do
  if [ -e "$SRC_ABS/$s" ] && [ ! -e "$DEST_ABS/$s" ]; then
    cp -p "$SRC_ABS/$s" "$DEST_ABS/$s"; echo "   copy $s"
  fi
done

echo; echo "== dry run (all)"
cd "$WF"
DRYLOG="$DEST_ABS/l1_dryrun.log"
"$SMK" -s "$WF/Snakefile" --configfile "$NEW_CONFIG" --rerun-triggers mtime -n all \
  > "$DRYLOG" 2>&1 || { tail -30 "$DRYLOG"; echo "ERROR: dry run failed" >&2; exit 1; }
# job table: lines "rule_name  count" between "Job stats:" and the total line
BAD=$(awk '/^Job stats:/{f=1;next} f&&/^total/{f=0} f{print $1}' "$DRYLOG" \
      | grep -E '^(score_sample|score|score_provenance|stamp_provenance|perm_sample_one|perm_null_one|perm_diff_one|perm_nulls|perm_nulls_diff|compare|compare_consensusq|detect_blacklist|merge_blacklist|bearing_sheet)$' || true)
awk '/^Job stats:/{f=1} f{print "   " $0} f&&/^total/{exit}' "$DRYLOG"
if [ -n "$BAD" ]; then
  echo "ERROR: the dry run would rebuild linked upstream products: $BAD" >&2
  echo "       They would write through the links into $SRC. Not submitting." >&2
  echo "       Check why (e.g. a newer config sheet or categories file): $DRYLOG" >&2
  exit 1
fi
echo "   OK: no score / perm / compare jobs; full dry-run log: $DRYLOG"
[ "$DRY" = 1 ] && { echo; echo "Dry run only."; exit 0; }

echo; echo "== submitting all -> $DEST"
"$SMK" -s "$WF/Snakefile" --configfile "$NEW_CONFIG" --rerun-triggers mtime \
  --profile "$PROFILE" all
echo; echo "Done -> workflow/$DEST (diff_stat l1). Compare with workflow/$SRC."
