#
# run_cluster_qnorm_l1.sh -- real-data scaling sensitivity run (C10, option b):
# the SAME run as a finished production l1 run, with within-sample per-track
# nonzero-quantile normalisation switched on before the composition is formed
# (config normalize: "--normalize-tracks --normalize-method nonzero-quantile",
# bigwig_to_qcat.normalize_signal_matrix). Observed scores AND every
# permutation round are normalised (score_sample and the perm rules both use
# _score_norm_flag), so the null matches. Everything is recomputed (scores
# change, so nothing can be linked from the source run).
#
# WHY: in the calibrated complementarity simulation (RNA q99/q50 matched to the
# real DN-3T3 tracks; claude/transform_benchmark_result_2026-11-08.md section 5)
# production l1 calls no CTCF->RAD21 switch while nzq calls 97-98% at s0.9 with
# 0-1 false calls per ~1,000. This run asks whether the real-data conclusions
# (DJ_RC, Igh, 3T3 genome-wide, lead tracks of the BH bins) change under nzq.
#
# Needs bigwig_to_qcat.py with the fast nonzero-quantile reference
# (2026-11-08); without it each normalised chromosome takes hours.
#
# WHAT IT DOES
#   1. Writes workflow/config/config_<dest>.generated.yaml = the base config
#      with outdir = DEST and normalize = nonzero-quantile (nothing else).
#   2. Preflight + dry run of the targets (default: the core targets below).
#   3. Submits (skip with --dry).
#
# USAGE (from the repository root; bearing env active)
#   bash workflow/run_cluster_qnorm_l1.sh \
#        --base-config workflow/config/config_results_prior1_n100_l1.generated.yaml [--dry]
#   V1P panel:
#   bash workflow/run_cluster_qnorm_l1.sh \
#        --base-config workflow/config/config_v1p7ar_prior1_l1.yaml \
#        --target pvalue.done --target calibration.done [--dry]
#   --dest NAME (default <base outdir>_qnorm); --target REL is relative to the
#   run folder and repeatable. Default targets: pvalue.done calibration.done
#   regional/significant_bins_summary.tsv
#   table_sources/regional_empirical_tcrb.tsv table_sources/regional_empirical_igh.tsv
#
# ASCII-only.

set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WF="$REPO/workflow"
PROFILE="$WF/profiles/slurm"
BASE=""; DEST=""; DRY=0; SMK=${SNAKEMAKE:-snakemake}
TREL=()
if [ -n "${PYTHONPATH:-}" ]; then
  echo "NOTE: clearing PYTHONPATH (was: $PYTHONPATH)"
  unset PYTHONPATH
fi
while [ $# -gt 0 ]; do
  case "$1" in
    --base-config) BASE="$2"; shift 2 ;;
    --dest) DEST="$2"; shift 2 ;;
    --target) TREL+=("$2"); shift 2 ;;
    --dry) DRY=1; shift ;;
    -h|--help) sed -n 2,48p "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done
[ -n "$BASE" ] || { echo "ERROR: --base-config <yaml of the finished l1 run> is required" >&2; exit 2; }
[ -f "$BASE" ] || { echo "ERROR: base config not found: $BASE" >&2; exit 1; }
grep -qF "ref_probs * (col.size - 1)" "$REPO/bigwig_to_qcat.py" \
  || { echo "ERROR: bigwig_to_qcat.py lacks the fast nonzero-quantile reference (2026-11-08 patch)" >&2; exit 1; }

BASE_OUT=$(python3 -c "import yaml,sys;print(yaml.safe_load(open(sys.argv[1]))['outdir'])" "$BASE")
[ -n "$DEST" ] || DEST="${BASE_OUT%/}_qnorm"
[ -e "$WF/$DEST" ] && [ "$(ls -A "$WF/$DEST" 2>/dev/null)" ] && \
  echo "NOTE: $WF/$DEST exists and is not empty; Snakemake will only build what is missing."
NEW="$WF/config/config_${DEST}.generated.yaml"
python3 - "$BASE" "$NEW" "$DEST" << 'PY'
import sys, yaml
base, new, dest = sys.argv[1:4]
cfg = yaml.safe_load(open(base))
if cfg.get("normalize"):
    sys.exit("ERROR: base config already normalises (%r)" % cfg["normalize"])
if str(cfg.get("diff_stat", "sum")) != "l1":
    sys.exit("ERROR: base config diff_stat is %r, expected l1" % cfg.get("diff_stat", "sum"))
print("  base : outdir %s  prior %s  n_perms %s  min_signal %s  pvalue_min_signal %s  diff_stat %s"
      % (cfg.get("outdir"), cfg.get("prior_strength"), cfg.get("n_perms"),
         cfg.get("min_signal"), cfg.get("pvalue_min_signal"), cfg.get("diff_stat")))
src = cfg.get("outdir")
cfg["outdir"] = dest
cfg["normalize"] = "--normalize-tracks --normalize-method nonzero-quantile"
cfg["cohort_reference"] = False
with open(new, "w") as fh:
    fh.write("# AUTO-GENERATED by run_cluster_qnorm_l1.sh 1.0.0 from %s.\n"
             "# Differs from it ONLY in: outdir (%s -> %s), normalize (nonzero-quantile).\n"
             % (base, src, dest))
    yaml.safe_dump(cfg, fh, default_flow_style=False, sort_keys=False)
print("  new  : %s (outdir %s, normalize nonzero-quantile)" % (new, dest))
PY

[ ${#TREL[@]} -eq 0 ] && TREL=(pvalue.done calibration.done regional/significant_bins_summary.tsv \
  table_sources/regional_empirical_tcrb.tsv table_sources/regional_empirical_igh.tsv)
TARGETS=()
for t in "${TREL[@]}"; do TARGETS+=("$WF/$DEST/$t"); done

cd "$WF"
echo; echo "== preflight"
python3 "$WF/preflight.py" --configfile "$NEW" --core-only
echo; echo "== dry run"
DRYLOG="$WF/${DEST}_dryrun.log"
"$SMK" -s "$WF/Snakefile" --configfile "$NEW" --rerun-triggers mtime -n "${TARGETS[@]}" \
  > "$DRYLOG" 2>&1 || { tail -30 "$DRYLOG"; echo "ERROR: dry run failed" >&2; exit 1; }
awk '/^Job stats:/{f=1} f{print "   " $0} f&&/^total/{exit}' "$DRYLOG"
echo "   full dry-run log: $DRYLOG"
[ "$DRY" = 1 ] && { echo; echo "Dry run only."; exit 0; }
echo; echo "== submitting -> $DEST"
"$SMK" -s "$WF/Snakefile" --configfile "$NEW" --rerun-triggers mtime \
  --profile "$PROFILE" --keep-going "${TARGETS[@]}"
echo; echo "Done -> workflow/$DEST. Compare with workflow/$BASE_OUT."
