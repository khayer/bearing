#!/usr/bin/env bash
# Build a tiny simulated dataset + config for an end-to-end workflow test.
#
#   bash workflow/test/make_sim_inputs.sh WORKDIR
#
# Writes into WORKDIR: 4 samples x 6 BigWigs on one 2 Mb chromosome (chrSim),
# two conditions (A, B) x two replicates, a sample sheet, regions, gene /
# annotation BEDs, and config.sim.yaml (layered on top of config/config.yaml).
# Condition B has its planted blocks shifted, so A vs B has real differences.
# ASCII only.
set -euo pipefail

WORK="${1:?usage: make_sim_inputs.sh WORKDIR}"
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
mkdir -p "$WORK"
WORK="$(cd "$WORK" && pwd)"
cd "$WORK"

CHROM=chrSim
LEN=2000000
TRACKS=(atac rnaplus rnaminus ctcf rad21 h3k27ac)

# name  condition  replicate  seed  start-offset (bins)
SAMPLES=(
  "A_rep1 A 1 11 500"
  "A_rep2 A 2 12 500"
  "B_rep1 B 1 21 2500"
  "B_rep2 B 2 22 2500"
)

printf "sample\tcondition\treplicate\tout\tbw\tcool\tinsul\tpca1\tloops\tresolutions\n" > samples.tsv
for row in "${SAMPLES[@]}"; do
  read -r name cond rep seed offset <<<"$row"
  if [[ ! -s "${name}_h3k27ac.bw" ]]; then
    python "$REPO/benchmark/simulate_bearing_tracks.py" --prefix "$name" \
      --chrom "$CHROM" --length "$LEN" --bin-size 200 --seed "$seed" \
      --start-offset-bins "$offset" > /dev/null
  fi
  bws=""
  for t in "${TRACKS[@]}"; do bws="${bws:+$bws,}$WORK/${name}_${t}.bw"; done
  printf "%s\t%s\t%s\t%s.qcat.bgz\t%s\t\t\t\t\t\n" "$name" "$cond" "$rep" "$name" "$bws" >> samples.tsv
done
cp A_rep1.chrom.sizes sim.chrom.sizes

# Regions / annotations on chrSim (planted blocks start at 100 kb for A and
# 500 kb for B; blocks are 5 kb with 15 kb gaps).
printf "name\tregion\tresolution\tlabel\n" > regions.tsv
printf "simA\t%s:80000-260000\t1000\tblocks in A\n" "$CHROM" >> regions.tsv
printf "simB\t%s:480000-660000\t1000\tblocks in B\n" "$CHROM" >> regions.tsv
{
  printf "%s\t100000\t105000\tGeneA1\t0\t+\n" "$CHROM"
  printf "%s\t120000\t125000\tGeneA2\t0\t-\n" "$CHROM"
  printf "%s\t500000\t505000\tGeneB1\t0\t+\n" "$CHROM"
  printf "%s\t900000\t910000\tGeneNull\t0\t+\n" "$CHROM"
} > genes.bed
printf "%s\t60000\t300000\tlocusA\n%s\t460000\t700000\tlocusB\n" "$CHROM" "$CHROM" > locus_regions.bed
printf "%s\t101000\t101100\tcbe1\n%s\t501000\t501100\tcbe2\n" "$CHROM" "$CHROM" > cbe.bed
: > blacklist_external.bed
# Two element classes for the element-class enrichment rule.
mkdir -p element_classes
printf "%s\t100000\t105000\tblkA1\n%s\t120000\t125000\tblkA2\n" "$CHROM" "$CHROM" > element_classes/planted.bed
printf "%s\t900000\t905000\tnull1\n%s\t950000\t955000\tnull2\n" "$CHROM" "$CHROM" > element_classes/background.bed

cat > config.sim.yaml <<YAML
# Simulated end-to-end test config (generated by make_sim_inputs.sh).
# Layer on top of the default config:
#   snakemake --configfile workflow/config/config.yaml $WORK/config.sim.yaml
bearing_dir: "$REPO"
outdir: "$WORK/results"
data_dir: "$WORK"
samples_sheet: "$WORK/samples.tsv"
chrom_sizes: "$WORK/sim.chrom.sizes"
regions_file: "$WORK/regions.tsv"
genes_bed: "$WORK/genes.bed"
agr_genes_bed: "$WORK/genes.bed"
cbe_bed: "$WORK/cbe.bed"
blacklist_external: "$WORK/blacklist_external.bed"
reference_condition: A
n_perms: 3
min_shift: 300000
pvalue_min_signal: 0.05
pvalue_null_min_bytes: 0     # null qcats here are ~350 KB, below the 1 MB genome-wide gate
floor_sweep_floors: [0.05, 0.1]
floor_sweep_threads: 2
paper_figures: false
paper_tables: false
regional_loci:
  sim:
    bed: "$WORK/locus_regions.bed"
    window: "$CHROM:0-1000000"
element_class_window: "$CHROM:0-1000000"
element_class_dir: "$WORK/element_classes"
element_classes: [planted, background]
YAML
echo "Simulated inputs ready in $WORK"
